  static void setResolvedLocale(Locale locale) {
    _activeLocale = locale;
  }

  static void clearResolvedLocale() {
    _activeLocale = null;
  }

  static Locale get _resolvedLocale {
    final activeLocale = _activeLocale;
    if (activeLocale != null) {
      return activeLocale;
    }
    try {
      return StorageService.getResolvedLocale();
    } catch (_) {
      return PlatformDispatcher.instance.locale;
    }
  }

  static bool get isEnglish => _resolvedLocale.languageCode == 'en';

  static bool get isRussian => _resolvedLocale.languageCode == 'ru';

  static String localize(String text, {Locale? locale}) {
    final targetLocale = locale ?? _resolvedLocale;
    final exactTable = switch (targetLocale.languageCode) {
      'en' => _exactEn,
      'ru' => _exactRu,
      _ => null,
    };
    if (exactTable == null) {
      return text;
    }
    final exact = exactTable[text];
    if (exact != null) {
      return exact;
    }
    final regexTable = switch (targetLocale.languageCode) {
      'en' => _regexEn,
      'ru' => _regexRu,
      _ => const <(RegExp, _TextRewriter)>[],
    };
    for (final (pattern, rewrite) in regexTable) {
      final match = pattern.firstMatch(text);
      if (match != null) {
        return rewrite(match);
      }
    }
    return text;
  }
